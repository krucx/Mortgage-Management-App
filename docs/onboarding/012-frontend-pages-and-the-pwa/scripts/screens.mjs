// Drives the real screens (vite's dev server, in front of the served sample book) in a
// headless browser, doing what lessons 1–5 have the reader do, and prints what each screen
// shows and which /api/ requests it makes: run by run_throughs.sh, which says how. Saves
// only on the scratch book run_throughs.sh made, in the lessons' order.
//
//   node screens.mjs <frontend url> <repo>
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const [, , base, repo] = process.argv
const { chromium } = createRequire(`${repo}/docs/sample-book/package.json`)('playwright')

const browser = await chromium.launch({ channel: process.env.CHROMIUM ? undefined : 'chrome' })
const context = await browser.newContext({ viewport: { width: 1280, height: 900 } })
const page = await context.newPage()
page.setDefaultTimeout(15000)
// The day of the book in the browser too, as the forms default to the browser's today.
await page.clock.setFixedTime(new Date('2026-10-19T11:00:00'))
// WhatsApp is never opened: the link it would open is printed instead.
await page.addInitScript(() => {
  window.__opened = []
  window.open = (url) => (window.__opened.push(String(url)), null)
})

let log = []
const clear = () => (log = [])
page.on('request', (request) => {
  const url = new URL(request.url())
  if (url.pathname.startsWith('/api/')) log.push(`${request.method()} ${url.pathname}${url.search}`)
})
const answers = []
page.on('response', async (response) => {
  const url = new URL(response.url())
  if (url.pathname.startsWith('/api/') && response.status() >= 400)
    answers.push(`${response.status()} ${url.pathname}: ${await response.text().catch(() => '')}`)
})

async function settle(ms = 900) {
  await page.waitForLoadState('networkidle')
  await page.waitForTimeout(ms)
}
function show(title) {
  console.log(`  -- ${title}: ${log.length} request(s)`)
  for (const line of log) console.log(`     ${line}`)
}
const text = async (locator) => (await locator.innerText()).replace(/\s+\n/g, '\n').trim()
const say = (label, value) => console.log(`  ${label}:`, typeof value === 'string' ? JSON.stringify(value) : value)
const dialog = () => page.getByRole('dialog')
const api = async (path) => (await fetch(`http://127.0.0.1:8000${path}`)).json()

